#!/usr/bin/env python3
"""CineVerse app icon ("Orbit"): a play button inside a tilted planet ring, with sparkles.

Single source for every platform. Run from the repo root:  python3 design/icon/generate_icons.py
  - Android (tvApp + androidApp): adaptive-icon vectors in res/drawable/ic_launcher_{background,foreground,monochrome}.xml
  - iOS: iosApp/iosApp/Assets.xcassets/AppIcon.appiconset/AppIcon-1024.png
  - Web: composeApp/src/wasmJsMain/resources/{favicon.ico,apple-touch-icon.png}
Geometry is in the 108-unit adaptive canvas; launchers show roughly 18..90, so the PNGs crop to that square.
Needs Pillow.
"""
import math
import os

from PIL import Image, ImageDraw

BG_START, BG_END = "#0E0B2A", "#3B2A7A"
PLAY, RING = "#F4EEFF", "#FFB86B"
TRIANGLE = [(46, 40), (46, 68), (70, 54)]
# Ring: ellipse centre, radii, rotation (degrees), stroke width.
RCX, RCY, RX, RY, ROT, RW = 54, 55, 29, 9, -22, 3
# Four-point sparkles: centre x, y, outer radius, inner radius.
SPARKLES = [(35, 36, 4.94, 1.95), (74, 73, 3.8, 1.5), (73, 35, 2.66, 1.05)]


def ring_point(t):
    r, t = math.radians(ROT), math.radians(t)
    x, y = RX * math.cos(t), RY * math.sin(t)
    return RCX + x * math.cos(r) - y * math.sin(r), RCY + x * math.sin(r) + y * math.cos(r)


def sparkle_points(cx, cy, ro, ri):
    return [(cx + (ro if i % 2 == 0 else ri) * math.cos(math.radians(i * 45)),
             cy + (ro if i % 2 == 0 else ri) * math.sin(math.radians(i * 45))) for i in range(8)]


# ---- Android vectors ----

def f(v):
    return f"{v:.3f}".rstrip("0").rstrip(".")


def poly_path(pts):
    return "M" + "L".join(f"{f(x)},{f(y)}" for x, y in pts) + "Z"


def ring_path(t0):
    """Half of the ring from parameter t0 to t0 + 180 (clockwise on screen)."""
    (x0, y0), (x1, y1) = ring_point(t0), ring_point(t0 + 180)
    return f"M{f(x0)},{f(y0)}A{RX},{RY} {ROT} 0,1 {f(x1)},{f(y1)}"


VECTOR_HEAD = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design/icon/generate_icons.py; edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"{extra}
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
"""


def fill(path, colour):
    return f'    <path\n        android:fillColor="{colour}"\n        android:pathData="{path}" />\n'


def stroke(path, colour):
    return (f'    <path\n        android:fillColor="#00000000"\n        android:pathData="{path}"\n'
            f'        android:strokeColor="{colour}"\n        android:strokeLineCap="round"\n'
            f'        android:strokeWidth="{RW}" />\n')


def foreground(play, ring):
    # Back half of the ring, then the play button, then the front half so the ring wraps around it.
    body = stroke(ring_path(180), ring) + fill(poly_path(TRIANGLE), play) + stroke(ring_path(0), ring)
    body += "".join(fill(poly_path(sparkle_points(*s)), play) for s in SPARKLES)
    return VECTOR_HEAD.format(extra="") + body + "</vector>\n"


def background():
    return VECTOR_HEAD.format(extra='\n    xmlns:aapt="http://schemas.android.com/aapt"') + f"""    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:endColor="{BG_END}"
                android:endX="108"
                android:endY="108"
                android:startColor="{BG_START}"
                android:startX="0"
                android:startY="0"
                android:type="linear" />
        </aapt:attr>
    </path>
</vector>
"""


# ---- PNG renderer (iOS, web) ----

def rgb(hex_colour):
    return tuple(int(hex_colour[i:i + 2], 16) for i in (1, 3, 5))


def render(px, ss=4):
    """Opaque px×px PNG of the visible 18..90 square."""
    n = px * ss
    u = n / 72.0

    def p(x, y):
        return (x - 18) * u, (y - 18) * u

    g = Image.new("L", (256, 256))
    g.putdata([(x + y) // 2 for y in range(256) for x in range(256)])
    # The background gradient spans 0..108; crop its 18..90 part.
    full = g.resize((round(n * 108 / 72),) * 2, Image.BILINEAR)
    off = round(18 * u)
    mask = full.crop((off, off, off + n, off + n))
    img = Image.composite(Image.new("RGB", (n, n), rgb(BG_END)), Image.new("RGB", (n, n), rgb(BG_START)), mask)
    d = ImageDraw.Draw(img)

    def ring_half(t0):
        r = RW / 2 * u
        steps = int(RX * math.pi * u / 2)  # one dot every ~2 px: a smooth round-capped stroke
        for i in range(steps + 1):
            x, y = p(*ring_point(t0 + 180 * i / steps))
            d.ellipse([x - r, y - r, x + r, y + r], fill=rgb(RING))

    ring_half(180)
    d.polygon([p(*q) for q in TRIANGLE], fill=rgb(PLAY))
    ring_half(0)
    for s in SPARKLES:
        d.polygon([p(*q) for q in sparkle_points(*s)], fill=rgb(PLAY))
    return img.resize((px, px), Image.LANCZOS)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as out:
        out.write(text)


def main():
    # Self-check: every foreground shape stays inside the 66-unit safe zone (radius 33 around 54,54).
    reach = [math.dist((54, 54), q) for q in TRIANGLE]
    reach += [math.dist((54, 54), ring_point(t)) + RW / 2 for t in range(0, 360, 2)]
    reach += [math.dist((54, 54), (cx, cy)) + ro for cx, cy, ro, _ in SPARKLES]
    assert max(reach) <= 33, f"foreground leaves the safe zone: {max(reach):.2f}"
    # And the PNG renderer agrees: (52,54) in canvas units is inside the play button.
    probe = render(72, ss=2)
    assert max(abs(a - b) for a, b in zip(probe.getpixel((52 - 18, 54 - 18)), rgb(PLAY))) < 8, "play button missing"

    for app in ("tvApp", "androidApp"):
        res = f"{app}/src/main/res/drawable"
        write(f"{res}/ic_launcher_background.xml", background())
        write(f"{res}/ic_launcher_foreground.xml", foreground(PLAY, RING))
        write(f"{res}/ic_launcher_monochrome.xml", foreground("#FFFFFFFF", "#FFFFFFFF"))

    render(1024).save("iosApp/iosApp/Assets.xcassets/AppIcon.appiconset/AppIcon-1024.png")  # RGB: iOS rejects alpha
    web = "composeApp/src/wasmJsMain/resources"
    render(180).save(f"{web}/apple-touch-icon.png")
    render(256).save(f"{web}/favicon.ico", sizes=[(16, 16), (32, 32), (48, 48)])
    print("icons written")


if __name__ == "__main__":
    main()
